export async function exportAsZip(
  files: ExportFiles,
  onProgress?: ZipGenerationCallback,
): Promise<void> {
  const zip = new JSZip();

  try {
    onProgress?.({
      stage: "Generating project template",
      progress: 0,
      total: 100,
    });

    const template = generateProjectTemplate(files);

    onProgress?.({
      stage: "Creating folder structure",
      progress: 20,
      total: 100,
    });

    template.folders.forEach((folder) => {
      zip.folder(folder);
    });

    onProgress?.({ stage: "Adding files", progress: 40, total: 100 });

    const fileEntries = Object.entries(template.files);
    fileEntries.forEach(([path, content], index) => {
      zip.file(path, content);

      const progress = 40 + Math.floor((index / fileEntries.length) * 40);
      onProgress?.({
        stage: `Adding files (${index + 1}/${fileEntries.length})`,
        progress,
        total: 100,
      });
    });

    onProgress?.({ stage: "Generating ZIP archive", progress: 80, total: 100 });

    const blob = await zip.generateAsync({
      type: "blob",
      compression: "DEFLATE",
      compressionOptions: { level: 6 },
    });

    onProgress?.({ stage: "Preparing download", progress: 95, total: 100 });

    const url = URL.createObjectURL(blob);
    const link = document.createElement("a");
    link.href = url;

    const date = new Date().toISOString().split("T")[0];
    const sanitizedName = files.projectName
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "");

    link.download = `${sanitizedName}-${date}.zip`;

    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    onProgress?.({ stage: "Complete", progress: 100, total: 100 });
  } catch (error) {
    console.error("Error generating ZIP:", error);
    throw new Error(
      `Failed to generate ZIP file: ${error instanceof Error ? error.message : "Unknown error"}`,
    );
  }
}

export async function copyToClipboard(text: string): Promise<boolean> {
  try {
    await navigator.clipboard.writeText(text);
    return true;
  } catch {
    const textarea = document.createElement("textarea");
    textarea.value = text;
    textarea.style.position = "fixed";
    textarea.style.left = "-9999px";
    document.body.appendChild(textarea);
    textarea.select();
    const success = document.execCommand("copy");
    document.body.removeChild(textarea);
    return success;
  }
}

export function formatForIDE(content: string): string {
  return content.replace(/\r\n/g, "\n").replace(/\r/g, "\n").trim();
}
