import JSZip from "jszip";
import { TechStackItemType } from "@blueprint/shared";

interface ExportFiles {
  blueprint: string;
  tasks: string;
  projectName: string;
  techStack?: TechStackItemType[];
  description?: string;
  targetAudience?: string;
  features?: string[];
}

interface ProjectTemplate {
  files: Record<string, string>;
  folders: string[];
  packageJson?: Record<string, any>;
  readme?: string;
}

export interface ZipGenerationProgress {
  stage: string;
  progress: number;
  total: number;
}

export type ZipGenerationCallback = (progress: ZipGenerationProgress) => void;

function generateProjectTemplate(files: ExportFiles): ProjectTemplate {
  const template: ProjectTemplate = {
    files: {},
    folders: [".docs", "src"],
  };

  template.files[".docs/blueprint.md"] = files.blueprint;
  template.files[".docs/task.md"] = files.tasks;
  template.files[".docs/README.md"] = `# ${files.projectName} - Documentation

This folder contains AI-generated documentation for your project.

## Files

- **blueprint.md** - Architectural blueprint and technical specifications
- **task.md** - Prioritized task breakdown for implementation

## Usage

These files are designed for use with autonomous development agents.
Place this .docs folder in your project root to enable agent-assisted development.

---
Generated by [Blueprint Generator](https://blueprint-generator.pages.dev)
Generated at: ${new Date().toISOString()}
`;

  if (files.techStack && files.techStack.length > 0) {
    const primaryStack = files.techStack[0];
    if (!primaryStack) return generateGenericTemplate(files);

    const stackCategory = primaryStack.category;

    switch (stackCategory) {
      case "frontend":
        if (
          files.techStack.some((t) => t.name.toLowerCase().includes("react"))
        ) {
          return generateReactTemplate(files);
        } else if (
          files.techStack.some((t) => t.name.toLowerCase().includes("vue"))
        ) {
          return generateVueTemplate(files);
        } else if (
          files.techStack.some((t) => t.name.toLowerCase().includes("angular"))
        ) {
          return generateAngularTemplate(files);
        }
        break;

      case "backend":
        if (
          files.techStack.some((t) => t.name.toLowerCase().includes("node"))
        ) {
          return generateNodeTemplate(files);
        } else if (
          files.techStack.some((t) => t.name.toLowerCase().includes("python"))
        ) {
          return generatePythonTemplate(files);
        } else if (
          files.techStack.some((t) => t.name.toLowerCase().includes("java"))
        ) {
          return generateJavaTemplate(files);
        }
        break;

      case "database":
        return generateDatabaseTemplate(files);

      case "hosting":
        return generateStaticSiteTemplate(files);

      case "ai":
        return generateGenericTemplate(files);

      case "testing":
        return generateGenericTemplate(files);

      case "styling":
        return generateStaticSiteTemplate(files);

      case "other":
        return generateGenericTemplate(files);
    }
  }

  return generateGenericTemplate(files);
}

